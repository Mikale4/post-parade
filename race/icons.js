  const cache = Object.create(null);
  function svgFor(name) {
    if (cache[name]) return cache[name];
    const ic = ICONS[name];
    if (!ic) return "";
    let rects = "";
    ic.r.forEach((row, y) => {
      for (let x = 0; x < row.length;) {
        const ch = row[x];
        if (ch === "." || !ic.p[ch]) { x++; continue; }
        let w = 1;
        while (row[x + w] === ch) w++;
        const fill = ic.p[ch] === "cur" ? "currentColor" : ic.p[ch];
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${fill}"/>`;
        x += w;
      }
    });
    return (cache[name] = rects);
  }

  /** An icon as inline SVG. Size comes from CSS (.ico is 1em) unless `size` is given. */
  function Icon(name, size, cls) {
    const body = svgFor(name);
    if (!body) return "";
    const sz = size ? ` width="${size}" height="${size}"` : "";
    return `<svg class="ico${cls ? " " + cls : ""}" viewBox="0 0 12 12"${sz} shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
  }
  Icon.names = Object.keys(ICONS);

  root.Icon = Icon;
